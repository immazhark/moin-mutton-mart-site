import {test,expect} from '@playwright/test';
test('privacy control clears the saved basket and invalidates another open counter',async({page,context})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Add Mutton with bone',exact:true}).click();
  await page.getByRole('button',{name:'Review request'}).click();
  const sheet=page.getByRole('dialog');
  await sheet.getByRole('button',{name:'Delivery',exact:true}).click();
  await sheet.getByText('Add a note (optional)',{exact:true}).click();
  await sheet.getByLabel('Order note').fill('Private example note');
  await sheet.getByRole('button',{name:'Check latest rates & availability'}).click();
  await expect(sheet.getByRole('link',{name:'Continue as unpriced enquiry'})).toBeVisible();
  const privacy=await context.newPage();
  await privacy.goto('/privacy/');
  await privacy.getByRole('button',{name:'Clear saved basket',exact:true}).click();
  await expect(privacy.getByRole('status')).toContainText('Saved basket cleared');
  await expect.poll(()=>privacy.evaluate(()=>localStorage.getItem('moin-request-v2'))).toBeNull();
  await expect(sheet.getByText('Nothing selected yet.')).toBeVisible();
  await expect(sheet.getByRole('link',{name:'Continue as unpriced enquiry'})).toHaveCount(0);
  await sheet.getByRole('button',{name:'Back to the counter'}).click();
  await page.getByRole('button',{name:'Add Mutton with bone',exact:true}).click();
  await page.getByRole('button',{name:'Review request'}).click();
  await expect(sheet.getByLabel('Order note')).toHaveValue('');
  await expect(sheet.getByRole('button',{name:'Not sure yet'})).toHaveAttribute('aria-pressed','true');
  await privacy.close();
});
test('removing the last item forgets order-level notes and fulfilment',async({page})=>{
  await page.goto('/');
  await page.getByRole('button',{name:'Add Mutton with bone',exact:true}).click();
  await page.getByRole('button',{name:'Review request'}).click();
  const sheet=page.getByRole('dialog');
  await sheet.getByRole('button',{name:'Delivery',exact:true}).click();
  await sheet.getByText('Add a note (optional)',{exact:true}).click();
  await sheet.getByLabel('Order note').fill('Old request note');
  await sheet.getByRole('button',{name:'Remove Mutton with bone'}).click();
  await sheet.getByRole('button',{name:'Back to the counter'}).click();
  await page.getByRole('button',{name:'Add Mutton with bone',exact:true}).click();
  await page.getByRole('button',{name:'Review request'}).click();
  await expect(sheet.getByLabel('Order note')).toHaveValue('');
  await expect(sheet.getByRole('button',{name:'Not sure yet'})).toHaveAttribute('aria-pressed','true');
});
